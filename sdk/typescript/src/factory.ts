import type { Client } from './interfaces.js';

/**
 * Detects whether the current runtime is inside a Wails desktop application
 * by checking for the presence of the Wails-generated `window.go` namespace.
 */
function isWailsRuntime(): boolean {
    return (
        typeof window !== 'undefined' &&
        typeof (window as unknown as Record<string, unknown>).go !== 'undefined'
    );
}

/**
 * Returns true when running inside a Wails desktop context.
 * This can be used to conditionally render UI elements that depend on
 * desktop-only features such as the embedded server or seal management.
 */
export function isDesktop(): boolean {
    return isWailsRuntime();
}

/** Configuration options for {@link getClient}. */
export interface ClientConfig {
    /** Base URL for the REST API (ignored in desktop mode). */
    readonly baseUrl?: string;
}

/**
 * Creates a {@link Client} instance appropriate for the current environment.
 *
 * In desktop (Wails) mode the returned client communicates via IPC bindings
 * generated by the Wails build toolchain. In browser mode the returned client
 * uses `fetch()` against the REST API at the given base URL.
 *
 * @param config - Optional configuration. The `baseUrl` field is required
 *   when running outside of a Wails context.
 * @returns A fully-configured Client instance.
 */
export async function getClient(config?: ClientConfig): Promise<Client> {
    if (isWailsRuntime()) {
        const { WailsClient } = await import('./wails.js');
        return new WailsClient();
    }
    const { RestClient } = await import('./rest.js');
    return new RestClient(config?.baseUrl ?? '');
}
