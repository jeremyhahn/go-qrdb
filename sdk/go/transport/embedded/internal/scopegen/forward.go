const (
	// transportPkg is the package whose client interfaces the forwarding
	// scope's methods come from.
	transportPkg = "github.com/jeremyhahn/go-qrdb/sdk/go/transport"

	// quicPkg is the package of the transport a forwarded call is sent with.
	quicPkg = "github.com/jeremyhahn/go-qrdb/sdk/go/transport/quic"
)

// forwardedFamilies are the SDK client interfaces a database-scoped embedded
// transport serves through the scoped data-plane services -- the calls a node
// that holds no replica of the database refuses -- and so forwards. They are
// the client side of the families adapters lists; the watch is a stream and
// is never forwarded.
var forwardedFamilies = []string{
	"KVClient",
	"GuardedKVClient",
	"MVCCClient",
	"TransactionClient",
	"BatchClient",
	"LeaseClient",
	"LockClient",
	"IndexClient",
	"TimeSeriesClient",
	"VectorClient",
	"CollectionClient",
	"VlogClient",
}

