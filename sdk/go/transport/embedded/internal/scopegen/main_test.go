// committed is the generated file, relative to this package.
const committed = "../../database_scope_services.go"

// The committed file is exactly what the generator produces from today's
// pkg/service interfaces: an interface that grew a method, or a hand edit to
// the file, fails here as well as in CI's check step.
func TestCommittedFileIsCurrent(t *testing.T) {
	if err := run("", committed); err != nil {
		t.Fatalf("%v", err)
	}
}

func TestCheckFile_ReportsDrift(t *testing.T) {
	src, err := generate()
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	stale := filepath.Join(t.TempDir(), "stale.go")
	if err := os.WriteFile(stale, append([]byte("// hand edit\n"), src...), 0o600); err != nil {
		t.Fatalf("write: %v", err)
	}
	var drift *DriftError
	if err := checkFile(stale, src); !errors.As(err, &drift) || drift.Path != stale {
		t.Fatalf("checkFile(stale) = %v, want *DriftError naming the file", err)
	}
	if !strings.Contains(drift.Error(), "go generate") {
		t.Errorf("drift error %q does not name the remedy", drift.Error())
	}
	var genErr *GenerateError
	if err := checkFile(filepath.Join(t.TempDir(), "missing.go"), src); !errors.As(err, &genErr) || genErr.Unwrap() == nil {
		t.Fatalf("checkFile(missing) = %v, want *GenerateError wrapping the read failure", err)
	}
}

func TestRun_CheckAndStdout(t *testing.T) {
	stale := filepath.Join(t.TempDir(), "stale.go")
	if err := os.WriteFile(stale, []byte("package embedded\n"), 0o600); err != nil {
		t.Fatalf("write: %v", err)
	}
	var drift *DriftError
	if err := run(filepath.Join(t.TempDir(), "never.go"), stale); !errors.As(err, &drift) {
		t.Fatalf("run(check stale) = %v, want *DriftError", err)
	}

	r, w, err := os.Pipe()
	if err != nil {
		t.Fatalf("pipe: %v", err)
	}
	stdout := os.Stdout
	os.Stdout = w
	runErr := run("", "")
	os.Stdout = stdout
	_ = w.Close()
	var got bytes.Buffer
	if _, err := got.ReadFrom(r); err != nil {
		t.Fatalf("read: %v", err)
	}
	if runErr != nil {
		t.Fatalf("run(stdout): %v", runErr)
	}
	want, _ := os.ReadFile(committed)
	if !bytes.Equal(got.Bytes(), want) {
		t.Fatal("stdout differs from the committed file")
	}
}

func TestRun_WritesTheGeneratedFile(t *testing.T) {
	out := filepath.Join(t.TempDir(), "out.go")
	if err := run(out, ""); err != nil {
		t.Fatalf("run: %v", err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	want, _ := os.ReadFile(committed)
	if !bytes.Equal(got, want) {
		t.Fatal("the written file differs from the committed one")
	}
	if !bytes.HasPrefix(got, []byte("// Code generated by scopegen; DO NOT EDIT.")) {
		t.Error("the generated file does not carry the generated-code marker")
	}
}

// Every context-free method is generated as a refusal, never resolved for a
// guessed tenant.
func TestGenerated_ContextFreeMethodsRefuse(t *testing.T) {
	src, err := generate()
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if strings.Contains(string(src), "context.Background()") {
		t.Fatal("a generated method resolves for a background context instead of refusing")
	}
	for _, m := range []string{"GetRetentionPolicy", "ListMetrics", "SetRetentionPolicy"} {
		if !strings.Contains(string(src), "// "+m+" refuses:") {
			t.Errorf("%s is not generated as a refusal", m)
		}
	}
}

func TestRender_RefusesAMissingInterface(t *testing.T) {
	var genErr *GenerateError
	if _, err := render(types.NewScope(nil, token.NoPos, token.NoPos, "empty")); !errors.As(err, &genErr) {
		t.Fatalf("render(empty scope) = %v, want *GenerateError", err)
	}
	if !strings.Contains(genErr.Error(), "KVServicer") {
		t.Errorf("error %q does not name the missing interface", genErr.Error())
	}
}

func TestRender_RefusesAMalformedInterface(t *testing.T) {
	pkg := types.NewPackage(servicePkg, "service")
	scope := types.NewScope(nil, token.NoPos, token.NoPos, "service")
	scope.Insert(types.NewTypeName(token.NoPos, pkg, "KVServicer", types.Typ[types.Int]))
	var genErr *GenerateError
	if _, err := render(scope); !errors.As(err, &genErr) || !strings.Contains(genErr.Error(), "not an interface") {
		t.Fatalf("render(non-interface) = %v, want *GenerateError", err)
	}

	noError := types.NewFunc(token.NoPos, pkg, "Get", types.NewSignatureType(nil, nil, nil, nil, nil, false))
	var b bytes.Buffer
	if err := renderMethod(&b, adapters[0], noError, nil); !errors.As(err, &genErr) || !strings.Contains(genErr.Error(), "does not return an error") {
		t.Fatalf("renderMethod(no error result) = %v, want *GenerateError", err)
	}
}

func TestZeroOf(t *testing.T) {
	cases := map[types.Type]string{
		types.Typ[types.Bool]:                  "false",
		types.Typ[types.String]:                `""`,
		types.Typ[types.Int64]:                 "0",
		types.NewSlice(types.Typ[types.Byte]):  "nil",
		types.NewPointer(types.Typ[types.Int]): "nil",
	}
	for typ, want := range cases {
		if got := zeroOf(typ, nil); got != want {
			t.Errorf("zeroOf(%s) = %s, want %s", typ, got, want)
		}
	}
	st := types.NewStruct(nil, nil)
	named := types.NewNamed(types.NewTypeName(token.NoPos, types.NewPackage("example.com/p", "p"), "T", nil), st, nil)
	if got := zeroOf(named, func(p *types.Package) string { return p.Name() }); got != "p.T{}" {
		t.Errorf("zeroOf(struct) = %s, want p.T{}", got)
	}
}

func TestWriteImportGroups(t *testing.T) {
	var b bytes.Buffer
	writeImportGroups(&b, map[string]string{
		"time":                    "time",
		"context":                 "context",
		"example.com/x/service":   "service",
		"example.com/renamed/pkg": "other",
	})
	want := "\t\"context\"\n\t\"time\"\n\n\tother \"example.com/renamed/pkg\"\n\t\"example.com/x/service\"\n"
	if b.String() != want {
		t.Fatalf("imports =\n%s\nwant\n%s", b.String(), want)
	}
}
