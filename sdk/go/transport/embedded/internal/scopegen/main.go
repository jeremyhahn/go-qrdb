// Command scopegen generates sdk/go/transport/embedded's
// database_scope_services.go: one adapter per data-plane service interface,
// each method resolving the service for the caller's (tenant, database)
// through the node's service.Registry and delegating.
//
// Its method sets are the pkg/service interfaces themselves, read with
// go/types, so an interface that grows a method changes the generated file,
// and `-check` (run by CI) fails until the file is regenerated. A method that
// takes no context cannot know the caller's tenant, so it is generated as a
// refusal (errScopedNeedsContext) rather than resolved for a guessed tenant;
// the transport resolves such calls itself.
//
// Usage, from sdk/go/transport/embedded (see the go:generate directive in
// database_scope.go):
//
//	go run ./internal/scopegen -o database_scope_services.go
//	go run ./internal/scopegen -check database_scope_services.go
