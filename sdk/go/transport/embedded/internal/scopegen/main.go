// servicePkg is the package whose interfaces the adapters implement.
const servicePkg = "github.com/jeremyhahn/go-qrdb/pkg/service"

// adapter is one generated type: the pkg/service interface it implements,
// the service.Registry method that resolves it, and its name.
type adapter struct {
	iface    string
	resolver string
	name     string
}

// adapters is every data-plane family a database-scoped transport confines.
