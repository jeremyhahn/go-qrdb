package main

import (
	"context"
	"time"

	sdk "github.com/jeremyhahn/go-qrdb/sdk/go"
	"github.com/jeremyhahn/go-qrdb/sdk/go/transport"
)

// InvitationBinding exposes invitation self-enrolment to the Wails frontend:
// Invite (authenticated, over the connected session) and Redeem
// (unauthenticated -- the invited user holds no credential yet, so Redeem
// dials its OWN connection rather than using the app's existing one).
type InvitationBinding struct {
	logger *sdk.ConcreteLogger
	conn   *ConnectionBinding
}

// NewInvitationBinding creates a new InvitationBinding backed by the given
// connection.
func NewInvitationBinding(log *sdk.ConcreteLogger, conn *ConnectionBinding) *InvitationBinding {
	return &InvitationBinding{logger: log, conn: conn}
}

// Invite creates a pending account in the connected session's own tenant --
// or re-invites one still pending -- and returns a single-use enrolment
// token exactly once.
func (b *InvitationBinding) Invite(req *transport.InviteUserRequest) (*transport.Invitation, error) {
	b.logger.Debug("Invite called")
	cl, err := b.conn.loadClient()
	if err != nil {
		b.logger.Error("Invite failed", "error", err)
		return nil, err
	}
	if !cl.SupportsInvitations() {
		err := &transport.CapabilityUnsupportedError{Message: "invitation self-enrolment is not carried on this transport"}
		b.logger.Error("Invite failed", "error", err)
		return nil, err
	}
	inv, err := cl.Invitations().InviteUser(context.Background(), req)
	if err != nil {
		b.logger.Error("Invite failed", "error", err)
		return nil, err
	}
	b.logger.Debug("Invite completed", "invitationID", inv.ID)
	return inv, nil
}

// RedeemInput asks the desktop to redeem an invitation against a server the
// invited user has no existing connection to -- Server/Transport/CAFile
// name where to dial, exactly as the CLI's --server/--transport/--ca-file do
// (see buildInvitationClient). CSRPEM is always required: the redeemer's key
// is generated by the caller (the frontend, via the Web Crypto API, or
// brought from elsewhere), never by this binding -- mirroring
// transport.InvitationClient.RedeemInvitation's own contract exactly, the
// same request shape on every transport.
type RedeemInput struct {
	Server    string `json:"server"`
	Transport string `json:"transport"`
	CAFile    string `json:"caFile,omitempty"`
	TenantID  string `json:"tenantID"`
	Token     string `json:"token"`
	CSRPEM    string `json:"csrPEM"`
	CertPEM   string `json:"certPEM,omitempty"`
	ChainPEM  string `json:"chainPEM,omitempty"`
}

// redeemTimeout bounds RedeemInput's one-off, unauthenticated connection and
// the redemption call itself, mirroring the CLI's --timeout default.
const redeemTimeout = 10 * time.Second

// Redeem redeems a one-time invitation token with NO existing connection or
// credential: the token is the authority.
func (b *InvitationBinding) Redeem(in *RedeemInput) (*transport.EnrolledCert, error) {
	b.logger.Debug("Redeem called")

	invitations, closeTransport, err := buildInvitationClient(in.Transport, in.Server, in.CAFile, redeemTimeout)
	if err != nil {
		b.logger.Error("Redeem failed", "error", err)
		return nil, err
	}
	defer func() { _ = closeTransport() }()

	enrolled, err := invitations.RedeemInvitation(context.Background(), &transport.RedeemInvitationRequest{
		TenantID: in.TenantID,
		Token:    in.Token,
		CSRPEM:   in.CSRPEM,
		CertPEM:  in.CertPEM,
		ChainPEM: in.ChainPEM,
	})
	if err != nil {
		b.logger.Error("Redeem failed", "error", err)
		return nil, err
	}
	b.logger.Debug("Redeem completed")
	return enrolled, nil
}
