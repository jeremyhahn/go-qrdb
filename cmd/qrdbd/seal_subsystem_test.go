// TestCeremonyCAFromBundle_NilBundle verifies that a nil bundle yields no
// CA and no error — the BYO-TLS posture where officer registration stays
// gated on the full initialization ceremony.
func TestCeremonyCAFromBundle_NilBundle(t *testing.T) {
	ca, err := ceremonyCAFromBundle(nil)
	assert.Nil(t, ca)
	assert.NoError(t, err)
}

// TestCeremonyCAFromBundle_NoCAKey verifies that a bundle without a CA
// private key (BYO TLS certificates) yields no CA and no error.
func TestCeremonyCAFromBundle_NoCAKey(t *testing.T) {
	bundle, err := generateCATLS()
	require.NoError(t, err)
	bundle.CAKeyPEM = nil

	ca, err := ceremonyCAFromBundle(bundle)
	assert.Nil(t, ca)
	assert.NoError(t, err)
}

// TestCeremonyCAFromBundle_AutoGenerated verifies that the auto-generated
// TLS bundle produces a working CeremonyCA whose signed officer
// certificates chain to the bundle's CA — the property the share-free
// officer claim flow depends on for mTLS client authentication.
func TestCeremonyCAFromBundle_AutoGenerated(t *testing.T) {
	bundle, err := generateCATLS()
	require.NoError(t, err)
	require.NotEmpty(t, bundle.CAKeyPEM, "auto-generated bundle must carry the CA key")

	ca, err := ceremonyCAFromBundle(bundle)
	require.NoError(t, err)
	require.NotNil(t, ca)

	// Sign a holder CSR with the custodian profile and verify the chain. The
	// identity comes from the options (the CA assigns it), not the CSR.
	officerKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	require.NoError(t, err)
	csrDER, err := x509.CreateCertificateRequest(rand.Reader, &x509.CertificateRequest{
		Subject: pkix.Name{CommonName: "chosen-by-the-requester"},
	}, officerKey)
	require.NoError(t, err)
	csrPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE REQUEST", Bytes: csrDER})

	cert, err := ca.SignCSR(context.Background(), csrPEM, &ceremony.SignCSROptions{
		TenantID:     "system",
		Username:     "so-1",
		Profile:      "custodian",
		ValidityDays: 365,
		KeyUsage:     x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
	})
	require.NoError(t, err)
	assert.Equal(t, "so-1", cert.Subject.CommonName)

	caBlock, _ := pem.Decode(bundle.CACertPEM)
	require.NotNil(t, caBlock)
	caCert, err := x509.ParseCertificate(caBlock.Bytes)
	require.NoError(t, err)
	assert.NoError(t, cert.CheckSignatureFrom(caCert))
}

// TestCeremonyCAFromBundle_CorruptCACert verifies that an unparseable CA
// certificate produces a CeremonyCAError wrapping the ceremony parse error.
func TestCeremonyCAFromBundle_CorruptCACert(t *testing.T) {
	bundle, err := generateCATLS()
	require.NoError(t, err)
	bundle.CACertPEM = []byte("not a certificate")

	ca, err := ceremonyCAFromBundle(bundle)
	assert.Nil(t, ca)
	var caErr *CeremonyCAError
	require.True(t, errors.As(err, &caErr), "expected *CeremonyCAError, got %T: %v", err, err)
	var parseErr *ceremony.CACertParseError
	assert.True(t, errors.As(err, &parseErr), "expected wrapped *ceremony.CACertParseError, got %v", err)
}

// TestCeremonyCAFromBundle_CorruptCAKey verifies that an unparseable CA
// key produces a CeremonyCAError wrapping the ceremony key parse error.
func TestCeremonyCAFromBundle_CorruptCAKey(t *testing.T) {
	bundle, err := generateCATLS()
	require.NoError(t, err)
	bundle.CAKeyPEM = []byte("not a key")

	ca, err := ceremonyCAFromBundle(bundle)
	assert.Nil(t, ca)
	var caErr *CeremonyCAError
	require.True(t, errors.As(err, &caErr), "expected *CeremonyCAError, got %T: %v", err, err)
	var parseErr *ceremony.CAKeyParseError
	assert.True(t, errors.As(err, &parseErr), "expected wrapped *ceremony.CAKeyParseError, got %v", err)
}

// TestCeremonyCAError verifies the Error and Unwrap contract.
func TestCeremonyCAError(t *testing.T) {
	inner := errors.New("boom")
	err := &CeremonyCAError{Err: inner}
	assert.Equal(t, "cli: ceremony CA construction failed: boom", err.Error())
	assert.ErrorIs(t, err, inner)
}
