// TestCeremonyCAError verifies the Error and Unwrap contract.
func TestCeremonyCAError(t *testing.T) {
	inner := errors.New("boom")
	err := &CeremonyCAError{Err: inner}
	assert.Equal(t, "cli: ceremony CA construction failed: boom", err.Error())
	assert.ErrorIs(t, err, inner)
}
