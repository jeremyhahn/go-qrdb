// TestBuildReturningStatement covers the RETURNING reattachment: the
// stripped clause parses via a throwaway SELECT and lands on the AST's
// Returning field for both DML kinds.
func TestBuildReturningStatement(t *testing.T) {
	h, _ := newResultColumnsHandler(t)

	del, err := h.buildReturningStatement("DELETE FROM `companies` WHERE `name` IN ('a','b')", `*`)
	require.NoError(t, err)
	deleteStmt, ok := del.(*sqlparser.Delete)
	require.True(t, ok)
	assert.Len(t, deleteStmt.Returning, 1)
	assert.True(t, statementCarriesReturning(del))

	upd, err := h.buildReturningStatement("UPDATE `users` SET `deleted_at`=? WHERE `name` = ?", `"id","name"`)
	require.NoError(t, err)
	updateStmt, ok := upd.(*sqlparser.Update)
	require.True(t, ok)
	assert.Len(t, updateStmt.Returning, 2)
	assert.True(t, statementCarriesReturning(upd))

	// A non-DML head is refused rather than silently dropped.
	_, err = h.buildReturningStatement("SELECT 1", `*`)
	require.Error(t, err)

	assert.False(t, statementCarriesReturning(nil))
}

// TestDeleteReturningExecutesEndToEnd proves the reattached AST actually
// plans and returns the deleted rows through the engine.
func TestDeleteReturningExecutesEndToEnd(t *testing.T) {
	h, ctx := newResultColumnsHandler(t)
	for _, q := range []string{
		"INSERT INTO people (id, name) VALUES (1, 'alice'), (2, 'bob'), (3, 'carol')",
	} {
		_, iter, _, err := h.sqlEngine.Query(ctx, q)
		require.NoError(t, err)
		_, _ = iter.Next(ctx)
		require.NoError(t, iter.Close(ctx))
	}

	head, returning, ok := engine.SplitUpdateDeleteReturning(
		`DELETE FROM "people" WHERE "id" IN (1, 2) RETURNING "id", "name"`)
	require.True(t, ok)
	translatedHead, err := h.translator.Translate(head)
	require.NoError(t, err)
	stmt, err := h.buildReturningStatement(translatedHead, returning)
	require.NoError(t, err)

	schema, iter, _, err := h.sqlEngine.QueryWithBindings(ctx, translatedHead, stmt, nil, nil)
	require.NoError(t, err)
	require.Len(t, schema, 2)
	assert.Equal(t, "id", schema[0].Name)

	var rows []sqlparser.Statement
	_ = rows
	count := 0
	for {
		row, err := iter.Next(ctx)
		if err != nil {
			break
		}
		count++
		assert.Len(t, row, 2)
	}
	require.NoError(t, iter.Close(ctx))
	assert.Equal(t, 2, count, "both deleted rows must be returned")

	// And the rows are genuinely gone.
	_, iter, _, err = h.sqlEngine.Query(ctx, "SELECT COUNT(*) FROM people")
	require.NoError(t, err)
	row, err := iter.Next(ctx)
	require.NoError(t, err)
	assert.EqualValues(t, 1, row[0])
	require.NoError(t, iter.Close(ctx))
}

// TestRewriteAddIdentity pins the ADD GENERATED ... AS IDENTITY rewrite.
func TestRewriteAddIdentity(t *testing.T) {
	got := rewriteAddIdentity(nil, nil, "",
		`ALTER TABLE public.log_usage ALTER COLUMN log_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.log_usage_log_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
)`)
	assert.Equal(t,
		"ALTER TABLE `log_usage` ALTER `log_id` SET DEFAULT (NEXTVAL('log_usage_log_id_seq'))", got)

	// Implicit sequence name when the options name none.
	got = rewriteAddIdentity(nil, nil, "",
		`ALTER TABLE "t" ALTER "c" ADD GENERATED ALWAYS AS IDENTITY`)
	assert.Equal(t, "ALTER TABLE `t` ALTER `c` SET DEFAULT (NEXTVAL('t_c_seq'))", got)

	// Non-identity statements pass through.
	assert.Equal(t, `ALTER TABLE "t" ADD COLUMN "c" bigint`,
		rewriteAddIdentity(nil, nil, "", `ALTER TABLE "t" ADD COLUMN "c" bigint`))
}

// TestSequenceDDLRecognition pins which statements handleSequenceDDL
// claims; the reset side effect itself is covered by the provider's
// sequence tests.
func TestSequenceDDLRecognition(t *testing.T) {
	for _, statement := range []string{
		`CREATE SEQUENCE IF NOT EXISTS events_uid_seq AS bigint`,
		`CREATE SEQUENCE "s1"`,
		`ALTER SEQUENCE events_uid_seq AS integer`,
		`DROP SEQUENCE IF EXISTS public.events_uid_seq CASCADE`,
	} {
		assert.Regexp(t, sequenceDDLRe, statement, statement)
	}
	assert.NotRegexp(t, sequenceDDLRe, `CREATE TABLE t (a int)`)
	assert.NotRegexp(t, sequenceDDLRe, `SELECT nextval('s1')`)
}
