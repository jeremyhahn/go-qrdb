// Package group implements IAM groups: named, tenant-scoped sets of roles
// that users join. A member's effective roles are its own RoleIDs union the
// RoleIDs of every group it belongs to (resolved at identity binding, see
// pkg/auth/middleware). Groups are not nested. Membership lives on the user
// record (pkg/user User.GroupIDs), so identity binding stays one record read.
package group

import "time"

// Group is a tenant-scoped set of roles that users are members of.
type Group struct {
	// ID is the globally unique UUID for this group, generated by the store.
	ID string `json:"id"`

	// TenantID identifies the tenant this group belongs to.
	TenantID string `json:"tenantID"`

	// Name is the human-readable group name, unique within a tenant.
	Name string `json:"name"`

	// Description is free text describing the group. Presentation only.
	Description string `json:"description,omitempty"`

	// RoleIDs lists the roles every member of the group holds. Every role is
	// a role of the group's own tenant.
	RoleIDs []string `json:"roleIDs"`

	// CreatedAt records when the group was created (UTC).
	CreatedAt time.Time `json:"createdAt"`

	// UpdatedAt records the last modification time (UTC).
	UpdatedAt time.Time `json:"updatedAt"`
}

// CreateGroupRequest holds the parameters for creating a group.
type CreateGroupRequest struct {
	// TenantID identifies the tenant. Defaults to the system tenant when empty.
	TenantID string

	// Name is the desired group name. Must not be empty.
	Name string

	// Description is optional free text.
	Description string

	// RoleIDs are the roles the group carries.
	RoleIDs []string
}

// UpdateGroupRequest holds the parameters for updating a group.
type UpdateGroupRequest struct {
	// ID is the group UUID to update. Required.
	ID string

	// Name replaces the current name when non-empty.
	Name string

	// Description replaces the current description when non-nil.
	Description *string

	// RoleIDs replaces the current role set when non-nil. An empty, non-nil
	// slice clears it.
	RoleIDs []string

	// Guard, when set, is judged against the record this write commits
	// over (prior) and the record it would write (next); an error aborts
	// the update with nothing written. The store commits by
	// CompareAndSwap on prior, so a record changed after the guard ran
	// fails with *GroupConflictError instead of being overwritten. Guard
	// must not modify either record.
	Guard func(prior, next *Group) error
}

// ListGroupsRequest holds the parameters for listing groups.
type ListGroupsRequest struct {
	// TenantID filters groups by tenant. Defaults to the system tenant.
	TenantID string

	// Page is the 1-based page number. Zero or negative defaults to 1.
	Page int

	// PageSize is the maximum number of groups per page. Zero or negative
	// defaults to defaultPageSize.
	PageSize int
}

// ListGroupsResponse holds a page of groups.
type ListGroupsResponse struct {
	// Groups is the page of group records.
	Groups []*Group `json:"groups"`

	// Total is the total number of groups matching the query.
	Total int `json:"total"`

	// HasMore is true when additional pages exist.
	HasMore bool `json:"hasMore"`
}
