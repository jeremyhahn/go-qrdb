const recoveryMetaKey = "recovery-meta"

// RecoveryKeyResult contains the output of recovery key generation. The
// Shares must be distributed to custodians for safekeeping. They are NOT
// persisted in storage -- only the metadata (threshold and total) is stored.
type RecoveryKeyResult struct {
	Shares      []string `json:"shares"`
	Threshold   int      `json:"threshold"`
	TotalShares int      `json:"total_shares"`
}

// recoveryMeta is the metadata persisted alongside the recovery key
// configuration. Only the threshold and total are stored; the share
// values themselves are never persisted.
type recoveryMeta struct {
	Threshold int `json:"threshold"`
	Total     int `json:"total"`
}

// GenerateRecoveryKeys generates a set of Shamir recovery shares from the
// barrier's root key. The shares are returned to the caller for distribution
// to custodians. Only the recovery metadata (threshold and total count) is
// persisted in the barrier's underlying storage.
//
// The barrier must be unsealed.
func (b *StorageBarrier) GenerateRecoveryKeys(ctx context.Context, threshold, total int) (*RecoveryKeyResult, error) {
	if threshold < 2 || total < threshold {
		return nil, ErrShamirThresholdInvalid
	}

	rootKey, err := b.GetMasterKey()
	if err != nil {
		return nil, err
	}
	defer secure.Wipe(rootKey)

	shares, err := shamir.Split(rootKey, threshold, total)
	if err != nil {
		return nil, ErrShamirSplitFailed
	}

	// Persist only the metadata (not the share values).
	meta := &recoveryMeta{
		Threshold: threshold,
		Total:     total,
	}
	metaBytes, err := json.Marshal(meta)
	if err != nil {
		return nil, err
	}
	if err := b.base.Put(ctx, recoveryMetaKey, metaBytes); err != nil {
		return nil, err
	}

	result := &RecoveryKeyResult{
		Shares:      make([]string, len(shares)),
		Threshold:   threshold,
		TotalShares: total,
	}
	for i, share := range shares {
		result.Shares[i] = share.Value
	}

	emitAudit(b.config.AuditLogger, "generate-recovery-keys", "barrier",
		b.config.RootKeyPath, "allow", map[string]string{
			"threshold": itoa(threshold),
			"total":     itoa(total),
		})

	return result, nil
}

// RecoverWithKeys unseals the barrier using recovery shares that were
// previously generated by GenerateRecoveryKeys. The provided share values
// must meet the threshold count stored in recovery metadata.
//
// The barrier must be in the sealed state. The recovery metadata must have
// been previously generated by GenerateRecoveryKeys.
//
// Recovery works by reconstructing the root key from shares, then using
// the ShamirStrategy (or a fallback software strategy) to unseal the
// EpochBarrier.
func (b *StorageBarrier) RecoverWithKeys(ctx context.Context, shareValues []string) error {
	if b.state.Load() == stateUnsealed {
		return ErrAlreadyUnsealed
	}

	// Load recovery metadata from raw storage (not encrypted).
	metaBytes, err := b.base.Get(ctx, recoveryMetaKey)
	if err != nil {
		return ErrRecoveryKeysNotFound
	}

	var meta recoveryMeta
	if err := json.Unmarshal(metaBytes, &meta); err != nil {
		return ErrRecoveryKeysNotFound
	}

	if len(shareValues) < meta.Threshold {
		return ErrShamirQuorumIncomplete
	}

	// Build Share objects for Shamir combine.
	shares := make([]*shamir.Share, len(shareValues))
	for i, val := range shareValues {
		shares[i] = &shamir.Share{
			Index:     i + 1,
			Threshold: meta.Threshold,
			Total:     meta.Total,
			Value:     val,
		}
	}

	rootKey, err := shamir.Combine(shares)
	if err != nil {
		return ErrShamirCombineFailed
	}
	defer secure.Wipe(rootKey)

	// Use unsealDirect to initialize/unseal the EpochBarrier with
	// the recovered root key.
	shamirStrat, ok := b.strategies[StrategyShamir]
	if !ok {
		// Create a temporary strategy to unseal.
		return b.recoverWithSoftwareStrategy(ctx, rootKey)
	}

	// Load the sealed root key data and unseal via recovery strategy.
	blob, getErr := b.base.Get(ctx, b.config.RootKeyPath)
	if getErr != nil {
		return getErr
	}
	var sealed SealedRootKey
	if jsonErr := json.Unmarshal(blob, &sealed); jsonErr != nil {
		return ErrCorruptRootKey
	}
	if setErr := b.barrier.SetSealedRootKey(&sealed); setErr != nil {
		return setErr
	}
	recStrat := newRecoveryStrategy(rootKey, shamirStrat)
	if unsealErr := b.barrier.Unseal(ctx, recStrat, Credentials{}); unsealErr != nil {
		return unsealErr
	}

	b.activeStrategy.Store(StrategyID("recovery"))
	b.state.Store(stateUnsealed)

	emitAudit(b.config.AuditLogger, "recover-with-keys", "barrier",
		b.config.RootKeyPath, "allow", map[string]string{
			"shares_provided": itoa(len(shareValues)),
			"threshold":       itoa(meta.Threshold),
		})

	return nil
}

// recoverWithSoftwareStrategy handles recovery when no ShamirStrategy is
// registered. It uses a recoveryStrategy wrapper to bypass the original
// strategy's UnsealRootKey (which may require credentials), since the
// root key has already been recovered from shares.
func (b *StorageBarrier) recoverWithSoftwareStrategy(ctx context.Context, rootKey []byte) error {
	blob, err := b.base.Get(ctx, b.config.RootKeyPath)
	if err != nil {
		return err
	}
	var sealed SealedRootKey
	if jsonErr := json.Unmarshal(blob, &sealed); jsonErr != nil {
		return ErrCorruptRootKey
	}

	// Find the original strategy for BarrierEncryptor delegation.
	delegate, ok := b.strategies[sealed.Strategy]
	if !ok {
		return ErrStrategyNotFound
	}

	if setErr := b.barrier.SetSealedRootKey(&sealed); setErr != nil {
		return setErr
	}

	// Use recoveryStrategy to inject the pre-recovered root key.
	recStrat := newRecoveryStrategy(rootKey, delegate)
	if unsealErr := b.barrier.Unseal(ctx, recStrat, Credentials{}); unsealErr != nil {
		return unsealErr
	}

	b.activeStrategy.Store(StrategyID("recovery"))
	b.state.Store(stateUnsealed)
	return nil
}

// recoveryStrategy wraps a pre-recovered root key so the EpochBarrier can
// be unsealed without going through the original strategy's KDF. This is
// needed because the original strategy may require credentials (e.g., a
// deferred-passphrase software strategy) that are not available during
// disaster recovery.
type recoveryStrategy struct {
	rootKey  []byte
	delegate SealingStrategy
}

func newRecoveryStrategy(rootKey []byte, delegate SealingStrategy) *recoveryStrategy {
	key := make([]byte, len(rootKey))
	copy(key, rootKey)
	return &recoveryStrategy{rootKey: key, delegate: delegate}
}

func (r *recoveryStrategy) ID() StrategyID       { return StrategyID("recovery") }
func (r *recoveryStrategy) Available() bool      { return true }
func (r *recoveryStrategy) HardwareBacked() bool { return false }
func (r *recoveryStrategy) Close() error         { secure.Wipe(r.rootKey); return nil }

func (r *recoveryStrategy) SealRootKey(_ context.Context, _ []byte, _ Credentials) (*SealedRootKey, error) {
	return nil, ErrAlreadyInitialized
}

func (r *recoveryStrategy) UnsealRootKey(_ context.Context, _ *SealedRootKey, _ Credentials) ([]byte, error) {
	key := make([]byte, len(r.rootKey))
	copy(key, r.rootKey)
	return key, nil
}

func (r *recoveryStrategy) BarrierEncryptor(ctx context.Context, rootKey []byte) (SymmetricEncrypter, error) {
	if r.delegate != nil {
		return r.delegate.BarrierEncryptor(ctx, rootKey)
	}
	return nil, nil
}

// DeleteRecoveryKeys removes the recovery key metadata from storage.
// The barrier must be unsealed.
func (b *StorageBarrier) DeleteRecoveryKeys(ctx context.Context) error {
	if b.IsSealed() {
		return ErrSealed
	}
	return b.base.Delete(ctx, recoveryMetaKey)
}

// HasRecoveryKeys reports whether recovery key metadata exists in storage.
// The barrier must be unsealed.
func (b *StorageBarrier) HasRecoveryKeys(ctx context.Context) (bool, error) {
	if b.IsSealed() {
		return false, ErrSealed
	}
	return b.base.Exists(ctx, recoveryMetaKey)
}

// itoa converts an int to a string without importing strconv.
func itoa(i int) string {
	if i == 0 {
		return "0"
	}
	if i < 0 {
		return "-" + uitoa(uint(-i))
	}
	return uitoa(uint(i))
}

// uitoa converts an unsigned int to a string.
func uitoa(u uint) string {
	if u == 0 {
		return "0"
	}
	var buf [20]byte
	i := len(buf)
	for u > 0 {
		i--
		buf[i] = byte('0' + u%10)
		u /= 10
	}
	return string(buf[i:])
}
