const recoveryMetaKey = "recovery-meta"

// RecoveryKeyResult contains the output of recovery key generation.
// Shares are sealed to enrolled recovery officers via the CeremonyDistributor
// and are never returned in this struct. Only metadata (threshold, total, and
// the officer share count) is reported. The share values are NOT persisted in
// storage.
type RecoveryKeyResult struct {
	ShareCount  int `json:"share_count"`
	Threshold   int `json:"threshold"`
	TotalShares int `json:"total_shares"`
}

// recoveryMeta is the metadata persisted alongside the recovery key
// configuration. Only the threshold and total are stored; the share
// values themselves are never persisted.
type recoveryMeta struct {
	Threshold int `json:"threshold"`
	Total     int `json:"total"`
}

// GenerateRecoveryKeys generates a set of Shamir recovery shares from the
// barrier's root key and seals them to the enrolled recovery officers via the
// recoveryDistributor. No share bytes are returned to the caller; only the
// metadata (threshold, total, share count) is reported.
// Only the recovery metadata (threshold and total count) is persisted in the
// barrier's underlying storage.
//
// ErrCeremonyDistributorNotConfigured is returned when no recovery distributor
// has been wired via SetRecoveryDistributor.
//
// The barrier must be unsealed.
func (b *StorageBarrier) GenerateRecoveryKeys(ctx context.Context, threshold, total int) (*RecoveryKeyResult, error) {
	if threshold < 2 || total < threshold {
		return nil, ErrShamirThresholdInvalid
	}
	if b.recoveryDistributor == nil {
		return nil, ErrCeremonyDistributorNotConfigured
	}

	rootKey, err := b.GetMasterKey()
	if err != nil {
		return nil, err
	}
	defer secure.Wipe(rootKey)

	// Persist only the metadata (not the share values).
	meta := &recoveryMeta{
		Threshold: threshold,
		Total:     total,
	}
	metaBytes, err := json.Marshal(meta)
	if err != nil {
		return nil, err
	}
	if err := b.base.Put(ctx, recoveryMetaKey, metaBytes); err != nil {
		return nil, err
	}

	shareCount, err := b.recoveryDistributor.SealAndDistribute(ctx, rootKey, threshold, total)
	if err != nil {
		return nil, err
	}

	emitAudit(b.config.AuditLogger, "generate-recovery-keys", "barrier",
		b.config.RootKeyPath, "allow", map[string]string{
			"threshold": itoa(threshold),
			"total":     itoa(total),
		})

	return &RecoveryKeyResult{
		ShareCount:  shareCount,
		Threshold:   threshold,
		TotalShares: total,
	}, nil
}

// RecoverWithKeys unseals the barrier using recovery shares that were
// previously generated by GenerateRecoveryKeys. The provided share values
// must meet the threshold count stored in recovery metadata.
//
// The barrier must be in the sealed state. The recovery metadata must have
// been previously generated by GenerateRecoveryKeys.
//
// Recovery works by reconstructing the root key from shares, then using
// the ShamirStrategy (or a fallback software strategy) to unseal the
// EpochBarrier.
func (b *StorageBarrier) RecoverWithKeys(ctx context.Context, shareValues []string) error {
	if b.state.Load() == stateUnsealed {
		return ErrAlreadyUnsealed
	}

	// Load recovery metadata from raw storage (not encrypted).
	metaBytes, err := b.base.Get(ctx, recoveryMetaKey)
	if err != nil {
		return ErrRecoveryKeysNotFound
	}

	var meta recoveryMeta
	if err := json.Unmarshal(metaBytes, &meta); err != nil {
		return ErrRecoveryKeysNotFound
	}

	if len(shareValues) < meta.Threshold {
		return ErrShamirQuorumIncomplete
	}

	// Each share is one mlock'd allocation against RLIMIT_MEMLOCK; destroy the
	// set on every path out of this function.
	shares := make([]*shamir.ProtectedShare, 0, len(shareValues))
	defer func() {
		for _, share := range shares {
			share.Destroy()
		}
	}()
	for i, val := range shareValues {
		// NewProtectedShare wipes raw as it enters protected memory on success;
		// wipe unconditionally so a validation failure (which leaves it
		// untouched) does not strand a plaintext copy on the heap. The caller's
		// string cannot be wiped (go-quicraft#35).
		raw := []byte(val)
		share, err := shamir.NewProtectedShare(i+1, meta.Threshold, meta.Total, raw)
		secure.Wipe(raw)
		if err != nil {
			return ErrShamirCombineFailed
		}
		shares = append(shares, share)
	}

	rootEnclave, err := shamir.CombineProtected(shares)
	if err != nil {
		return ErrShamirCombineFailed
	}
	defer rootEnclave.Destroy()

	// Copy the recovered root key into a protected buffer and run the recovery
	// OUTSIDE the enclave borrow: barrier.Unseal allocates protected memory,
	// which deadlocks if run inside WithBytes (see copyEnclaveToBuffer in
	// shamir.go). The buffer is destroyed as soon as recovery returns. Nothing
	// below retains rootKey — newRecoveryStrategy copies it into its own
	// protected enclave and stampNoneOriginSealedState only reads — which was
	// already the contract the deferred wipe imposed.
	rootBuf, err := copyEnclaveToBuffer(rootEnclave)
	if err != nil {
		return err
	}
	defer rootBuf.Destroy()
	// The alias spans storage I/O, a JSON decode and newRecoveryStrategyFn,
	// which copies the key into an enclave of its own: a protected allocation
	// that rule 6 keeps out of a borrow. The same holds on the
	// recoverWithSoftwareStrategy path (go-qrdb#428).
	//
	//secure:unborrowed allocates-protected newRecoveryStrategyFn copies rootKey into its own enclave
	rootKey := rootBuf.Bytes()

	// Use unsealDirect to initialize/unseal the EpochBarrier with the recovered
	// root key.
	shamirStrat, ok := b.strategyByID(StrategyShamir)
	if !ok {
		// Create a temporary strategy to unseal.
		return b.recoverWithSoftwareStrategy(ctx, rootKey)
	}

	// Load the sealed root key data and unseal via recovery strategy.
	blob, getErr := b.base.Get(ctx, b.config.RootKeyPath)
	if getErr != nil {
		return getErr
	}
	var sealed SealedRootKey
	if jsonErr := json.Unmarshal(blob, &sealed); jsonErr != nil {
		return ErrCorruptRootKey
	}
	if stampErr := b.stampNoneOriginSealedState(rootKey, &sealed); stampErr != nil {
		return stampErr
	}
	if setErr := b.barrier.SetSealedRootKey(&sealed); setErr != nil {
		return setErr
	}
	// newRecoveryStrategy COPIES the root key into a protected enclave that only
	// Close destroys, and Barrier.Unseal does not retain the strategy — it calls
	// UnsealRootKey and drops it. So without this Close the copy outlives the
	// enclave it was taken from, on both the success and the failure path, which
	// would defeat the protected-memory guarantee this change is making (found
	// in review of go-qrdb#46).
	recStrat, recErr := newRecoveryStrategyFn(rootKey, shamirStrat)
	if recErr != nil {
		return recErr
	}
	defer func() { _ = recStrat.Close() }()
	if unsealErr := b.barrier.Unseal(ctx, recStrat, Credentials{}); unsealErr != nil {
		return unsealErr
	}

	b.activeStrategy.Store(StrategyID("recovery"))
	b.state.Store(stateUnsealed)

	emitAudit(b.config.AuditLogger, "recover-with-keys", "barrier",
		b.config.RootKeyPath, "allow", map[string]string{
			"shares_provided": itoa(len(shareValues)),
			"threshold":       itoa(meta.Threshold),
		})

	return nil
}

// recoverWithSoftwareStrategy handles recovery when no ShamirStrategy is
// registered. It uses a recoveryStrategy wrapper to bypass the original
// strategy's UnsealRootKey (which may require credentials), since the
// root key has already been recovered from shares.
func (b *StorageBarrier) recoverWithSoftwareStrategy(ctx context.Context, rootKey []byte) error {
	blob, err := b.base.Get(ctx, b.config.RootKeyPath)
	if err != nil {
		return err
	}
	var sealed SealedRootKey
	if jsonErr := json.Unmarshal(blob, &sealed); jsonErr != nil {
		return ErrCorruptRootKey
	}

	// Find the original strategy for BarrierEncryptor delegation.
	delegate, ok := b.strategyByID(sealed.Strategy)
	if !ok {
		return ErrStrategyNotFound
	}

	if stampErr := b.stampNoneOriginSealedState(rootKey, &sealed); stampErr != nil {
		return stampErr
	}
	if setErr := b.barrier.SetSealedRootKey(&sealed); setErr != nil {
		return setErr
	}

	// Use recoveryStrategy to inject the pre-recovered root key.
	// As above: the strategy's protected copy of the root key is destroyed by
	// Close, and nothing else destroys it.
	recStrat, recErr := newRecoveryStrategyFn(rootKey, delegate)
	if recErr != nil {
		return recErr
	}
	defer func() { _ = recStrat.Close() }()
	if unsealErr := b.barrier.Unseal(ctx, recStrat, Credentials{}); unsealErr != nil {
		return unsealErr
	}

	b.activeStrategy.Store(StrategyID("recovery"))
	b.state.Store(stateUnsealed)
	return nil
}

// recoveryStrategy wraps a pre-recovered root key so the EpochBarrier can
// be unsealed without going through the original strategy's KDF. This is
// needed because the original strategy may require credentials (e.g., a
// deferred-passphrase software strategy) that are not available during
// disaster recovery.
type recoveryStrategy struct {
	// rootKey holds the pre-recovered root key in protected memory for the
	// whole barrier-unseal operation, not an ordinary heap []byte. The most
	// sensitive recovery material must live in an mlock'd, guard-paged enclave
	// while the strategy is alive, and be genuinely wiped by Close — a plain
	// slice cleared only at the end left it in collectable memory for the
	// duration (found in review of go-qrdb#46).
	rootKey  *secure.Secret
	delegate SealingStrategy
}

// newRecoveryStrategyFn is indirected so a test can observe the temporary
// strategy the recovery paths build and assert its protected copy of the root
// key is destroyed. The strategy is created and discarded inside those
// functions, so there is no other seam through which the cleanup can be
// verified — and verifying it matters, because Close is the only thing that
// destroys that copy (go-qrdb#46).
var newRecoveryStrategyFn = newRecoveryStrategy

func newRecoveryStrategy(rootKey []byte, delegate SealingStrategy) (*recoveryStrategy, error) {
	// Copy into a throwaway buffer NewSecret takes ownership of and wipes, so
	// the caller's borrowed rootKey is left intact and no extra plaintext copy
	// outlives this call.
	key := make([]byte, len(rootKey))
	copy(key, rootKey)
	sec, err := secure.NewSecret(key)
	if err != nil {
		secure.Wipe(key)
		return nil, &ShamirError{Sentinel: ErrShamirSplitFailed, Op: "protect recovery key", Cause: err}
	}
	return &recoveryStrategy{rootKey: sec, delegate: delegate}, nil
}

func (r *recoveryStrategy) ID() StrategyID       { return StrategyID("recovery") }
func (r *recoveryStrategy) Available() bool      { return true }
func (r *recoveryStrategy) HardwareBacked() bool { return false }
func (r *recoveryStrategy) Close() error         { r.rootKey.Destroy(); return nil }

func (r *recoveryStrategy) SealRootKey(_ context.Context, _ []byte, _ Credentials) (*SealedRootKey, error) {
	return nil, ErrAlreadyInitialized
}

func (r *recoveryStrategy) UnsealRootKey(_ context.Context, _ *SealedRootKey, _ Credentials) ([]byte, error) {
	// Borrow the protected key only for the moment it takes to hand a copy to
	// Barrier.Unseal, which owns and wipes the returned slice. The enclave is
	// re-sealed the instant the buffer is destroyed.
	//
	// The copy runs inside a COORDINATED borrow (go-qrdb#74): the earlier
	// Size-then-Bytes pair took two separate borrows with a gap between, and a
	// concurrent destroy (a shutdown enclave.WipeAll) landing in that gap would
	// have handed Barrier.Unseal a correctly sized run of zeros. secure.CopyOut
	// holds one borrow across the copy and refuses an empty source, so a
	// destroyed enclave fails the unseal instead of silently unsealing with
	// nothing.
	//
	// Traced callees: CopyOut's callback is make + copy. Nothing here reaches a
	// SealingStrategy or the store, which is what makes THIS site convertible
	// while Recover's own rootKey read (recovery.go, above) is not.
	buf, err := r.rootKey.Open()
	if err != nil {
		return nil, &ShamirError{Sentinel: ErrShamirCombineFailed, Op: "open recovery key", Cause: err}
	}
	defer buf.Destroy()
	key, err := secure.CopyOut(buf)
	if err != nil {
		return nil, &ShamirError{Sentinel: ErrShamirCombineFailed, Op: "read recovery key", Cause: err}
	}
	return key, nil
}

func (r *recoveryStrategy) BarrierEncryptor(ctx context.Context, rootKey []byte) (SymmetricEncrypter, error) {
	if r.delegate != nil {
		return r.delegate.BarrierEncryptor(ctx, rootKey)
	}
	return nil, nil
}

// DeleteRecoveryKeys removes the recovery key metadata from storage.
// The barrier must be unsealed.
func (b *StorageBarrier) DeleteRecoveryKeys(ctx context.Context) error {
	if b.IsSealed() {
		return ErrSealed
	}
	return b.base.Delete(ctx, recoveryMetaKey)
}

// HasRecoveryKeys reports whether recovery key metadata exists in storage.
// The barrier must be unsealed.
func (b *StorageBarrier) HasRecoveryKeys(ctx context.Context) (bool, error) {
	if b.IsSealed() {
		return false, ErrSealed
	}
	return b.base.Exists(ctx, recoveryMetaKey)
}

// itoa converts an int to a string without importing strconv.
func itoa(i int) string {
	if i == 0 {
		return "0"
	}
	if i < 0 {
		return "-" + uitoa(uint(-i))
	}
	return uitoa(uint(i))
}

// uitoa converts an unsigned int to a string.
func uitoa(u uint) string {
	if u == 0 {
		return "0"
	}
	var buf [20]byte
	i := len(buf)
	for u > 0 {
		i--
		buf[i] = byte('0' + u%10)
		u /= 10
	}
	return string(buf[i:])
}

// stampNoneOriginSealedState stamps the metadata MAC onto a sealed
// root-key record that legitimately carries none. quicraft's Initialize
// deliberately leaves a StrategyNone-sealed blob unstamped -- that strategy
// keeps no root key at rest to derive the MAC key from -- but every
// recovery-shaped unseal here runs the full MAC verification with the
// RECONSTRUCTED root key in hand. Stamping with that key upgrades the blob
// to authenticated metadata rather than refusing a state the none strategy
// itself defines as valid. Any other blob -- already stamped, or produced
// by a key-holding strategy -- is left untouched, so a stripped or
// tampered MAC on those still fails closed inside Unseal.
func (b *StorageBarrier) stampNoneOriginSealedState(rootKey []byte, sealed *SealedRootKey) error {
	if sealed == nil || len(sealed.StateMAC) != 0 || sealed.Strategy != StrategyNone {
		return nil
	}
	return quicraftseal.StampSealedStateMACWithRootKey(rootKey, b.config.DeploymentID, sealed)
}
