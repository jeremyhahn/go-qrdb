# devcontainer-pins.sh — write build/docker/devcontainer/compose.pins.yaml, the
# compose overlay that hands GO_IMAGE and TRIVY_IMAGE to the devcontainer
# build. VS Code runs compose directly (not make), and the Dockerfile's global
# FROM ${GO_IMAGE} / FROM ${TRIVY_IMAGE} have no default, so .devcontainer.json
# runs this as its initializeCommand. scripts/tool-pins.sh stays the one source
# of the pin values; the overlay is generated and gitignored.

set -eu

cd "$(dirname "$0")/.."

# shellcheck source=tool-pins.sh
. ./scripts/tool-pins.sh

if [ -z "${GO_IMAGE:-}" ]; then
	echo "devcontainer-pins: GO_IMAGE is empty in scripts/tool-pins.sh" >&2
	exit 1
fi
if [ -z "${TRIVY_IMAGE:-}" ]; then
	echo "devcontainer-pins: TRIVY_IMAGE is empty in scripts/tool-pins.sh" >&2
	exit 1
fi

out=build/docker/devcontainer/compose.pins.yaml
tmp=$(mktemp build/docker/devcontainer/.compose.pins.yaml.XXXXXX)
trap 'rm -f "$tmp"' EXIT INT TERM

cat >"$tmp" <<EOF
# Generated by scripts/devcontainer-pins.sh from scripts/tool-pins.sh; do not
# edit. VS Code's initializeCommand rewrites it before every container build.
services:
  devcontainer:
    build:
      args:
        GO_IMAGE: "${GO_IMAGE}"
        TRIVY_IMAGE: "${TRIVY_IMAGE}"
EOF

chmod 644 "$tmp"
mv "$tmp" "$out"
trap - EXIT INT TERM
